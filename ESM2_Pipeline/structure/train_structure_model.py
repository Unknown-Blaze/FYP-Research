"""
Structure-Based MHC-Peptide Binding Prediction Training
Uses PDB files generated by LocalColabFold to train binding affinity prediction

Requirements:
- All MHC PDB files in data/generated_pdbs/mhc/
- All peptide PDB files in data/generated_pdbs/peptide/
- row_to_pdb_map.json (maps dataset rows to PDB IDs)
"""

import pandas as pd
import numpy as np
import torch
import torch.nn as nn
from torch.utils.data import Dataset, DataLoader
from pathlib import Path
import json
from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_squared_error, r2_score, mean_absolute_error
import logging
from datetime import datetime

# Setup logging to both console and file
log_file = f"training_log_{datetime.now().strftime('%Y%m%d_%H%M%S')}.txt"
logging.basicConfig(
    level=logging.INFO,
    format='%(asctime)s - %(message)s',
    handlers=[
        logging.FileHandler(log_file),
        logging.StreamHandler()
    ]
)
logger = logging.getLogger(__name__)

# ============================================================================
# Configuration
# ============================================================================

CONFIG = {
    'dataset_path': '../iedb_dataset.csv',
    'pdb_dir_mhc': 'data/generated_pdbs/mhc',
    'pdb_dir_peptide': 'data/generated_pdbs/peptide',
    'mapping_file': 'row_to_pdb_map.json',
    'batch_size': 32,
    'num_epochs': 50,
    'learning_rate': 0.001,
    'device': 'cuda' if torch.cuda.is_available() else 'cpu'
}

# ============================================================================
# PDB Feature Extraction
# ============================================================================

def extract_ca_atoms(pdb_file):
    """Extract CA (alpha carbon) atom coordinates from PDB file"""
    coords = []
    
    with open(pdb_file, 'r') as f:
        for line in f:
            if line.startswith('ATOM') and ' CA ' in line:
                try:
                    x = float(line[30:38].strip())
                    y = float(line[38:46].strip())
                    z = float(line[46:54].strip())
                    coords.append([x, y, z])
                except:
                    continue
    
    return np.array(coords) if coords else np.array([[0, 0, 0]])

def compute_structure_features(coords):
    """Compute structural features from CA coordinates"""
    
    if len(coords) <= 1:
        return {
            'num_residues': 0,
            'radius_of_gyration': 0.0,
            'max_distance': 0.0,
            'contact_density': 0.0
        }
    
    # Center of mass
    com = coords.mean(axis=0)
    
    # Radius of gyration
    rg = np.sqrt(((coords - com) ** 2).sum(axis=1).mean())
    
    # Pairwise distances
    from scipy.spatial.distance import pdist, squareform
    dist_matrix = squareform(pdist(coords))
    
    # Max distance
    max_dist = dist_matrix.max()
    
    # Contact density (contacts within 8Å)
    contacts = (dist_matrix < 8.0).sum() - len(coords)  # Exclude diagonal
    total_pairs = len(coords) * (len(coords) - 1)
    contact_density = contacts / total_pairs if total_pairs > 0 else 0.0
    
    return {
        'num_residues': len(coords),
        'radius_of_gyration': float(rg),
        'max_distance': float(max_dist),
        'contact_density': float(contact_density)
    }

def get_pdb_features(pdb_id, pdb_dir):
    """Get structure features from PDB file"""
    
    # Find rank_001 file (best prediction)
    pdb_files = list(Path(pdb_dir).glob(f'{pdb_id}_*rank_001*.pdb'))
    
    if not pdb_files:
        logger.warning(f"PDB not found: {pdb_id}")
        return {
            'num_residues': 0,
            'radius_of_gyration': 0.0,
            'max_distance': 0.0,
            'contact_density': 0.0
        }
    
    coords = extract_ca_atoms(pdb_files[0])
    return compute_structure_features(coords)

# ============================================================================
# Dataset
# ============================================================================

class StructureBindingDataset(Dataset):
    def __init__(self, df, mapping, pdb_dir_mhc, pdb_dir_peptide):
        self.df = df.reset_index(drop=True)
        self.mapping = mapping
        self.pdb_dir_mhc = Path(pdb_dir_mhc)
        self.pdb_dir_peptide = Path(pdb_dir_peptide)
        
        # Pre-cache features
        logger.info("Caching structure features...")
        self.features_cache = {}
        
        for idx in range(len(self.df)):
            key = str(idx)
            if key in self.mapping:
                mhc_id = self.mapping[key]['mhc_pdb_id']
                pep_id = self.mapping[key]['peptide_pdb_id']
                
                if mhc_id not in self.features_cache:
                    self.features_cache[mhc_id] = get_pdb_features(mhc_id, self.pdb_dir_mhc)
                
                if pep_id not in self.features_cache:
                    self.features_cache[pep_id] = get_pdb_features(pep_id, self.pdb_dir_peptide)
        
        logger.info(f"Cached {len(self.features_cache)} unique structures")
    
    def __len__(self):
        return len(self.df)
    
    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        key = str(idx)
        
        # Get structure features
        if key in self.mapping:
            mhc_id = self.mapping[key]['mhc_pdb_id']
            pep_id = self.mapping[key]['peptide_pdb_id']
            
            mhc_feat = self.features_cache.get(mhc_id, {
                'num_residues': 0, 'radius_of_gyration': 0.0,
                'max_distance': 0.0, 'contact_density': 0.0
            })
            
            pep_feat = self.features_cache.get(pep_id, {
                'num_residues': 0, 'radius_of_gyration': 0.0,
                'max_distance': 0.0, 'contact_density': 0.0
            })
        else:
            # Fallback if mapping missing
            mhc_feat = pep_feat = {
                'num_residues': 0, 'radius_of_gyration': 0.0,
                'max_distance': 0.0, 'contact_density': 0.0
            }
        
        # Combine features
        features = torch.tensor([
            mhc_feat['num_residues'] / 400.0,  # Normalize
            mhc_feat['radius_of_gyration'] / 50.0,
            mhc_feat['max_distance'] / 100.0,
            mhc_feat['contact_density'],
            pep_feat['num_residues'] / 20.0,
            pep_feat['radius_of_gyration'] / 20.0,
            pep_feat['max_distance'] / 50.0,
            pep_feat['contact_density'],
            len(row['Peptide']) / 20.0,  # Peptide length
        ], dtype=torch.float32)
        
        # Target: binding affinity
        ic50 = float(row['IC50'])
        
        return features, ic50

# ============================================================================
# Model
# ============================================================================

class StructureBindingModel(nn.Module):
    def __init__(self, input_dim=9):
        super().__init__()
        
        self.net = nn.Sequential(
            nn.Linear(input_dim, 128),
            nn.ReLU(),
            nn.Dropout(0.3),
            nn.Linear(128, 64),
            nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(64, 32),
            nn.ReLU(),
            nn.Linear(32, 1)
        )
    
    def forward(self, x):
        return self.net(x).squeeze()

# ============================================================================
# Training
# ============================================================================

def train_epoch(model, loader, optimizer, criterion, device):
    model.train()
    total_loss = 0
    
    for features, targets in loader:
        features = features.to(device)
        targets = targets.to(device)
        
        optimizer.zero_grad()
        outputs = model(features)
        loss = criterion(outputs, targets)
        loss.backward()
        optimizer.step()
        
        total_loss += loss.item()
    
    return total_loss / len(loader)

def evaluate(model, loader, device):
    model.eval()
    predictions = []
    actuals = []
    
    with torch.no_grad():
        for features, targets in loader:
            features = features.to(device)
            outputs = model(features)
            
            predictions.extend(outputs.cpu().numpy())
            actuals.extend(targets.numpy())
    
    predictions = np.array(predictions)
    actuals = np.array(actuals)
    
    mse = mean_squared_error(actuals, predictions)
    rmse = np.sqrt(mse)
    r2 = r2_score(actuals, predictions)
    
    return rmse, r2, predictions, actuals

# ============================================================================
# Main
# ============================================================================

def main():
    logger.info("=" * 70)
    logger.info("STRUCTURE-BASED MHC-PEPTIDE BINDING PREDICTION")
    logger.info("=" * 70)
    logger.info("")
    
    # Load dataset
    logger.info("Loading dataset...")
    df = pd.read_csv(CONFIG['dataset_path'])
    logger.info(f"  Total samples: {len(df)}")
    
    # Load mapping
    logger.info("Loading PDB mapping...")
    with open(CONFIG['mapping_file'], 'r') as f:
        mapping = json.load(f)
    logger.info(f"  Mapped rows: {len(mapping)}")
    
    # Check PDB availability
    pdb_dir_mhc = Path(CONFIG['pdb_dir_mhc'])
    pdb_dir_peptide = Path(CONFIG['pdb_dir_peptide'])
    
    mhc_pdbs = len(list(pdb_dir_mhc.glob('*rank_001*.pdb')))
    pep_pdbs = len(list(pdb_dir_peptide.glob('*rank_001*.pdb')))
    
    logger.info(f"  Available MHC structures: {mhc_pdbs}")
    logger.info(f"  Available peptide structures: {pep_pdbs}")
    logger.info("")
    
    if mhc_pdbs == 0 or pep_pdbs == 0:
        logger.error("❌ No PDB files found! Run GENERATE_STRUCTURES.sh first")
        return
    
    # Train/test split
    train_df, test_df = train_test_split(df, test_size=0.2, random_state=42)
    logger.info(f"Train samples: {len(train_df)}")
    logger.info(f"Test samples:  {len(test_df)}")
    logger.info("")
    
    # Create datasets
    logger.info("Creating datasets...")
    train_dataset = StructureBindingDataset(train_df, mapping, pdb_dir_mhc, pdb_dir_peptide)
    test_dataset = StructureBindingDataset(test_df, mapping, pdb_dir_mhc, pdb_dir_peptide)
    
    train_loader = DataLoader(train_dataset, batch_size=CONFIG['batch_size'], shuffle=True)
    test_loader = DataLoader(test_dataset, batch_size=CONFIG['batch_size'])
    
    # Model
    device = torch.device(CONFIG['device'])
    logger.info(f"Using device: {device}")
    
    model = StructureBindingModel().to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=CONFIG['learning_rate'])
    criterion = nn.MSELoss()
    
    logger.info("")
    logger.info("Starting training...")
    logger.info("-" * 70)
    
    best_rmse = float('inf')
    best_r2 = float('-inf')
    test_predictions_best = None
    test_actuals_best = None
    
    for epoch in range(CONFIG['num_epochs']):
        train_loss = train_epoch(model, train_loader, optimizer, criterion, device)
        test_rmse, test_r2, preds, actuals = evaluate(model, test_loader, device)
        
        if test_rmse < best_rmse:
            best_rmse = test_rmse
            best_r2 = test_r2
            test_predictions_best = preds
            test_actuals_best = actuals
            torch.save(model.state_dict(), 'best_structure_model.pth')
        
        if (epoch + 1) % 5 == 0:
            logger.info(f"Epoch {epoch+1:3d} | Loss: {train_loss:.4f} | "
                       f"Test RMSE: {test_rmse:.4f} | R²: {test_r2:.4f}")
    
    logger.info("-" * 70)
    logger.info(f"✓ Training complete!")
    logger.info(f"  Best Test RMSE: {best_rmse:.4f}")
    logger.info(f"  Best Test R²: {best_r2:.4f}")
    logger.info(f"  MAE: {mean_absolute_error(test_actuals_best, test_predictions_best):.4f}")
    logger.info(f"  Model saved: best_structure_model.pth")
    logger.info(f"  Log file: {log_file}")
    logger.info("")
    
    # Save detailed results for paper
    results = {
        'timestamp': datetime.now().isoformat(),
        'test_rmse': float(best_rmse),
        'test_r2': float(best_r2),
        'test_mae': float(mean_absolute_error(test_actuals_best, test_predictions_best)),
        'n_samples': len(df),
        'n_train': len(train_df),
        'n_test': len(test_df),
        'n_features': 9,
        'model_params': sum(p.numel() for p in model.parameters()),
        'epochs': CONFIG['num_epochs'],
        'batch_size': CONFIG['batch_size'],
        'learning_rate': CONFIG['learning_rate'],
        'device': str(device)
    }
    
    results_file = f"training_results_{datetime.now().strftime('%Y%m%d_%H%M%S')}.json"
    with open(results_file, 'w') as f:
        json.dump(results, f, indent=2)
    logger.info(f"Results saved: {results_file}")

if __name__ == '__main__':
    main()
